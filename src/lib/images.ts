// Работа с адресами загруженных фото. Модуль без серверных зависимостей: его можно
// использовать и в браузерных компонентах.

const MAIN_RE = /^(\/uploads\/[0-9a-f-]{36})\.webp$/;

/**
 * Адрес уменьшенной копии фото (до 720 px) для карточек и превью.
 * У старых фото в JPG и PNG уменьшенной копии нет, для них возвращается исходный адрес.
 */
export function thumbUrl(url: string) {
  return url.replace(MAIN_RE, "$1-thumb.webp");
}
